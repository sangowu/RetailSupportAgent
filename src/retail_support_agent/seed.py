"""Provision the demo's accounts into the database at boot.

`identities` maps a token's subject to a retail identity, and the subject is generated by
the user pool. Terraform knows it and the database does not, so Terraform writes the
mapping into the instance's environment and this runs once per boot, after the migrations
and before the API and the UI start.

Boot rather than apply, for two reasons. Terraform has no route to this database: it sits
on a compose network on the instance. And the database is a container volume, so a volume
that is reset leaves a working user pool and an empty `identities` table, which would
refuse every sign-in with a 403 that looks like a defect. Seeding at boot repairs that
without an apply.

A subject is an opaque identifier, not a credential. Nothing here reads a password or a
token, and the mapping travels in the environment file beside the region and the image tag.
"""

from __future__ import annotations

import json
import os
import sys
from collections.abc import Iterable, Mapping
from dataclasses import dataclass
from typing import Any

from retail_support_agent.auth import ROLE_PERMISSIONS

# The environment variable Terraform writes. Absent or empty means there is nothing to
# provision, which is the local stack and every developer machine.
VARIABLE = "RSA_IDENTITIES"

# `demo` is the role the service invents for itself when authentication is not
# configured, and it carries `session:reset_all`. Granting it to a real subject would
# hand a signed-in visitor the power to drop everyone else's sessions, so it is not
# grantable here whatever the configuration says.
NOT_GRANTABLE = frozenset({"demo"})


class SeedError(Exception):
    """The mapping is not usable. Raised rather than skipped: a typo in a role name
    produces an account with no powers, which is indistinguishable from an authorization
    defect when someone is looking at a 403."""


@dataclass(frozen=True)
class Account:
    subject: str
    user_id: str
    roles: tuple[str, ...]


def parse(raw: str | None) -> list[Account]:
    """Read the mapping, or raise `SeedError`. An absent or empty value is not an error."""
    if raw is None or not raw.strip():
        return []
    try:
        loaded: Any = json.loads(raw)
    except json.JSONDecodeError as exc:
        raise SeedError(f"{VARIABLE} is not valid JSON: {exc.msg}.") from None
    if not isinstance(loaded, list):
        raise SeedError(f"{VARIABLE} must be a list of accounts.")
    return [_account(entry, position) for position, entry in enumerate(loaded)]


def _account(entry: Any, position: int) -> Account:
    where = f"{VARIABLE}[{position}]"
    if not isinstance(entry, Mapping):
        raise SeedError(f"{where} is not an object.")
    subject = entry.get("subject")
    user_id = entry.get("user_id")
    if not isinstance(subject, str) or not subject:
        raise SeedError(f"{where} has no subject.")
    if not isinstance(user_id, str) or not user_id:
        raise SeedError(f"{where} has no user_id.")
    raw_roles = entry.get("roles") or []
    if not isinstance(raw_roles, list) or not all(isinstance(role, str) for role in raw_roles):
        raise SeedError(f"{where} has roles that are not a list of strings.")
    for role in raw_roles:
        if role in NOT_GRANTABLE:
            raise SeedError(f"{where} grants {role!r}, which is not grantable.")
        if role not in ROLE_PERMISSIONS:
            raise SeedError(f"{where} grants {role!r}, which is not a role.")
    return Account(subject=subject, user_id=user_id, roles=tuple(raw_roles))


def apply(store: Any, accounts: Iterable[Account]) -> list[str]:
    """Write each account, and return one line per account for the boot log.

    `provision_identity` is idempotent in both halves, so a boot that changes nothing
    writes nothing. Roles that were granted here and later revoked by hand are not
    restored silently: revocation removes a row, and this adds the rows the configuration
    names, so a revoked role does come back on the next boot. That is stated because it
    is a real limit - a revocation that must outlive a restart belongs in the
    configuration, not in a one-off command.
    """
    written: list[str] = []
    for account in accounts:
        store.provision_identity(account.subject, account.user_id, account.roles)
        written.append(f"{account.subject} -> {account.user_id} {list(account.roles)}")
    return written


def main() -> int:
    """Entry point for the image's `seed` role."""
    from retail_support_agent.api import make_store
    from retail_support_agent.config import Settings

    try:
        accounts = parse(os.getenv(VARIABLE))
    except SeedError as exc:
        print(f"seed: {exc}", file=sys.stderr)
        return 2

    if not accounts:
        print(f"seed: {VARIABLE} is not set; nothing to provision.")
        return 0

    settings = Settings()  # type: ignore[call-arg]
    store = make_store(settings)
    if store is None:
        print("seed: no database is configured; identities live in one.", file=sys.stderr)
        return 2

    for line in apply(store, accounts):
        print(f"seed: {line}")
    return 0


if __name__ == "__main__":  # pragma: no cover - exercised through the entrypoint
    raise SystemExit(main())
