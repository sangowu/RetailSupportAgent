"""Regenerate evaluation/tau2_manifest.json and the task-set lists from the local
pinned checkout.

The manifest is generated reproducibly rather than maintained by hand. Run this
when the upstream commit changes or a fact needs re-checking, then review the
output with git diff.

Digests are computed over the bytes as upstream committed them:
`scripts/fetch_tau2.py` checks out with `core.autocrlf=false`, so Windows and
Linux produce the same SHA256 values.

Usage:
    uv run python scripts/fetch_tau2.py --verify-only   # confirm the checkout is clean
    uv run python scripts/regen_manifest.py
"""

from __future__ import annotations

import collections
import json
import re
import subprocess
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from retail_support_agent.tau2_pin import (
    DEFAULT_CHECKOUT,
    MANIFEST_PATH,
    REPO_ROOT,
    TASK_SETS_DIR,
    sha256_of,
)

# The pinned file list: policy, data, splits, simulated-user guidelines, the retail
# implementation and the evaluators.
PINNED_FILES = [
    "LICENSE",
    "data/tau2/domains/retail/db.json",
    "data/tau2/domains/retail/policy.md",
    "data/tau2/domains/retail/tasks.json",
    "data/tau2/domains/retail/split_tasks.json",
    "data/tau2/user_simulator/simulation_guidelines.md",
    "src/tau2/domains/retail/tools.py",
    "src/tau2/domains/retail/data_model.py",
    "src/tau2/domains/retail/environment.py",
    "src/tau2/domains/retail/utils.py",
    "src/tau2/evaluator/evaluator.py",
    "src/tau2/evaluator/evaluator_env.py",
    "src/tau2/evaluator/evaluator_nl_assertions.py",
]

# Write tools covered by the three flows this project declares (lookup, cancel, return)
IN_SCOPE_WRITE = frozenset({"cancel_pending_order", "return_delivered_order_items"})
ALL_WRITE = frozenset(
    {
        "cancel_pending_order",
        "return_delivered_order_items",
        "exchange_delivered_order_items",
        "modify_pending_order_items",
        "modify_pending_order_address",
        "modify_pending_order_payment",
        "modify_user_address",
    }
)


def git_out(checkout: Path, *args: str) -> str:
    return subprocess.run(
        ["git", *args], cwd=checkout, capture_output=True, text=True, check=True
    ).stdout.strip()


def scope_label(actions: list[dict[str, Any]]) -> str:
    """Classify a task by the write tools among its scored actions."""
    if not actions:
        return "no_action"
    writes = {a["name"] for a in actions} & ALL_WRITE
    if not writes:
        return "read_only"
    return "in_scope_write" if writes <= IN_SCOPE_WRITE else "out_of_scope_write"


def write_json(path: Path, payload: dict[str, Any]) -> None:
    path.write_text(
        json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n"
    )


def build(checkout: Path) -> None:
    commit = git_out(checkout, "rev-parse", "HEAD")
    commit_date = git_out(checkout, "log", "-1", "--format=%ad", "--date=iso-strict")

    tools_src = (checkout / "src/tau2/domains/retail/tools.py").read_text(encoding="utf-8")
    tools = [
        {"name": name, "type": kind.split(".")[-1]}
        for kind, name in re.findall(r"@is_tool\((\w+\.\w+)\)\s*\n\s*def (\w+)", tools_src)
    ]

    retail = checkout / "data/tau2/domains/retail"
    tasks: list[dict[str, Any]] = json.loads((retail / "tasks.json").read_text(encoding="utf-8"))
    split: dict[str, list[str]] = json.loads(
        (retail / "split_tasks.json").read_text(encoding="utf-8")
    )

    labels: dict[str, str] = {}
    reward_basis: collections.Counter[str] = collections.Counter()
    for task in tasks:
        criteria = task.get("evaluation_criteria") or {}
        reward_basis[",".join(criteria.get("reward_basis") or [])] += 1
        labels[task["id"]] = scope_label(criteria.get("actions") or [])

    train, test = split["train"], split["test"]
    if set(train) & set(test):
        raise SystemExit("the upstream train/test split overlaps; the protocol is unusable")
    if len(split["base"]) != len(tasks):
        raise SystemExit("the base split does not match the task count; the protocol is unusable")

    manifest = {
        "$comment": (
            "Pinned record of upstream τ²-bench, generated by scripts/regen_manifest.py. "
            "Do not edit by hand. Digests are over the bytes as upstream committed them "
            "(LF), so they match across platforms."
        ),
        "generated_at": "2026-09-06",
        "upstream": {
            "name": "Sierra tau2-bench",
            "repo": "https://github.com/sierra-research/tau2-bench",
            "tag": "v1.0.1",
            "commit": commit,
            "commit_date": commit_date,
            "license": "MIT",
            "copyright": "Copyright (c) 2025 Sierra Research",
            "attribution": (
                "The data, tools, policy and evaluators are upstream's work. This project "
                "only calls them and must not present them as its own implementation."
            ),
        },
        "domain": {
            "name": "retail",
            "policy_file": "data/tau2/domains/retail/policy.md",
            "db_file": "data/tau2/domains/retail/db.json",
            "tasks_file": "data/tau2/domains/retail/tasks.json",
            "split_file": "data/tau2/domains/retail/split_tasks.json",
            "solo_mode_supported": False,
            "tool_count": len(tools),
            "tools": tools,
        },
        "tasks": {
            "total": len(tasks),
            "splits": {"base": len(split["base"]), "train": len(train), "test": len(test)},
            "reward_basis_distribution": dict(reward_basis),
            "scope_label_counts": dict(collections.Counter(labels.values())),
        },
        "scoring": {
            "reward_rule": "the active components are multiplied; which apply comes from "
            "the task's reward_basis",
            "retail_basis": "112 tasks use DB + NL_ASSERTION, 2 use DB only",
            "db_component": "compares the final database state "
            "(src/tau2/evaluator/evaluator_env.py)",
            "nl_assertion_component": (
                "LLM judge (src/tau2/evaluator/evaluator_nl_assertions.py); the judge model "
                "is fixed and does not change with the model under test"
            ),
            "note": "the communicate and action components are not in retail's reward_basis "
            "and are diagnostic only.",
        },
        "files_sha256": {rel: sha256_of(checkout / rel) for rel in PINNED_FILES},
    }
    write_json(MANIFEST_PATH, manifest)

    write_json(
        TASK_SETS_DIR / "full.json",
        {
            "$comment": (
                "The full set is upstream's base split (train + test) in upstream order. "
                "Only all 114 tasks may be called a standard τ²-bench Retail score; "
                "dev and holdout are subsets and a subset score must not stand in for it."
            ),
            "source": "tau2-bench v1.0.1 split_tasks.json:base",
            "count": len(split["base"]),
            "task_ids": split["base"],
        },
    )
    write_json(
        TASK_SETS_DIR / "dev.json",
        {
            "$comment": "The dev set is upstream's train split. Only this set may be used "
            "for selection, tuning and prompt iteration.",
            "source": "tau2-bench v1.0.1 split_tasks.json:train",
            "count": len(train),
            "task_ids": train,
        },
    )
    write_json(
        TASK_SETS_DIR / "holdout.json",
        {
            "$comment": "The holdout is upstream's test split. It is used only for "
            "independent verification of a shortlisted configuration, never for tuning.",
            "source": "tau2-bench v1.0.1 split_tasks.json:test",
            "count": len(test),
            "task_ids": test,
        },
    )
    write_json(
        TASK_SETS_DIR / "scope_labels.json",
        {
            "$comment": "Business-scope labels for layered reporting. They change neither "
            "the upstream tasks nor the scoring, only how results are sliced.",
            "definitions": {
                "read_only": "the scored actions use no write tool",
                "in_scope_write": (
                    f"writes limited to {sorted(IN_SCOPE_WRITE)}, the cancel and return "
                    "scope this project declares"
                ),
                "out_of_scope_write": "writes such as modify, exchange, address or payment "
                "changes, outside the three declared flows",
                "no_action": "upstream gives no scored action",
            },
            "counts": dict(collections.Counter(labels.values())),
            "labels": labels,
        },
    )
    # regression.json records tasks that failed in a real run and is maintained by the
    # evaluation process, so it is not overwritten here.

    print(f"regenerated the manifest and task sets at {commit[:12]} (regression.json unchanged)")
    print(f"output directory: {REPO_ROOT / 'evaluation'}")


if __name__ == "__main__":
    if not (DEFAULT_CHECKOUT / ".git").is_dir():
        raise SystemExit(
            f"upstream checkout not found: {DEFAULT_CHECKOUT} (run scripts/fetch_tau2.py first)"
        )
    build(DEFAULT_CHECKOUT)
