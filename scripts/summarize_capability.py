"""Summarize raw probe records into a capability matrix.

The matrix is generated from the raw records rather than typed by hand: a typed
table cannot be traced back to a specific request, so it offers no evidence when
a conclusion is questioned.

Usage:
    uv run python scripts/summarize_capability.py                # latest run
    uv run python scripts/summarize_capability.py --run 20260906T123218Z
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from retail_support_agent.tau2_pin import REPO_ROOT

RUNS_ROOT = REPO_ROOT / "evaluation" / "capability_checks"

# Baseline probe -> the findings field that decides whether it passed
BASELINE_CHECKS: dict[str, str] = {
    "basic": "callable",
    "tool_call": "order_id_is_string",
    "tool_result_roundtrip": "answered_after_tool_result",
    "stream_usage": "usage_in_stream",
    "sampling_params": "accepted",
    "truncation": "signals_length_limit",
    "thinking_off": "thinking_actually_off",
}

EFFORT_LEVELS = ("minimal", "low", "medium", "high", "xhigh", "max")


def load_run(run_dir: Path) -> dict[str, dict[str, Any]]:
    """Load every model record of one run, indexed by probe name."""
    models: dict[str, dict[str, Any]] = {}
    for path in sorted(run_dir.glob("*.json")):
        if path.name == "summary.json":
            continue
        report = json.loads(path.read_text(encoding="utf-8"))
        models[report["model_id_requested"]] = {
            outcome["name"]: outcome for outcome in report["outcomes"]
        }
    return models


def mark(outcome: dict[str, Any] | None, key: str) -> str:
    if outcome is None:
        return "—"
    if outcome["status"] != "ok":
        return "✗"
    return "✓" if outcome.get("findings", {}).get(key) else "✗"


def table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines)


def build_markdown(run_id: str, models: dict[str, dict[str, Any]]) -> str:
    names = list(models)
    parts: list[str] = [
        f"# Model capability matrix (run {run_id})",
        "",
        "Generated by `scripts/summarize_capability.py` from the raw probe records. "
        "Do not edit by hand.",
        "",
        "## Baseline capabilities",
        "",
        table(
            ["probe", *names],
            [
                [probe, *[mark(models[m].get(probe), key) for m in names]]
                for probe, key in BASELINE_CHECKS.items()
            ],
        ),
        "",
        "## reasoning_effort levels: accepted, and measured reasoning_tokens",
        "",
    ]

    rows: list[list[str]] = []
    for level in EFFORT_LEVELS:
        row = [level]
        for model in names:
            outcome = models[model].get(f"reasoning_effort_{level}")
            if outcome is None:
                row.append("—")
            elif outcome["status"] != "ok":
                row.append("rejected")
            else:
                tokens = outcome["findings"].get("reasoning_tokens")
                row.append("accepted / no thinking" if tokens is None else f"accepted / {tokens}")
        rows.append(row)
    parts += [table(["level", *names], rows), ""]

    parts += ["## Thinking budget each level maps to (read from server errors)", ""]
    rows = []
    for level in EFFORT_LEVELS:
        row = [level]
        for model in names:
            outcome = models[model].get(f"effort_budget_mapping_{level}")
            findings = (outcome or {}).get("findings", {})
            mapped = findings.get("mapped_thinking_budget")
            if outcome is None:
                row.append("—")
            elif findings.get("level_unsupported"):
                row.append("unsupported")
            elif mapped is not None:
                row.append(str(mapped))
            else:
                row.append("not revealed")
        rows.append(row)
    parts += [
        table(["level", *names], rows),
        "",
        '"not revealed" means the level ran within a 512-token output cap, so the '
        "server never printed a budget. It does not mean the budget is zero.",
        "",
        "## Thinking budget and the mutual-exclusion rule",
        "",
    ]

    rows = []
    for model in names:
        budget = models[model].get("thinking_budget_64", {})
        bf = budget.get("findings", {})
        mutual = models[model].get("thinking_mutual_exclusion", {})
        mf = mutual.get("findings", {})
        within = bf.get("within_budget")
        rows.append(
            [
                model,
                str(bf.get("reasoning_tokens", "—")),
                {True: "respected", False: "exceeded", None: "-"}[within],
                "rejected" if mf.get("server_rejects_both") else "silently accepted",
                str(mf.get("winner", "—")),
            ]
        )
    parts += [
        table(
            [
                "model",
                "thinking tokens at budget=64",
                "cap respected",
                "both parameters sent",
                "parameter that took effect",
            ],
            rows,
        ),
        "",
    ]
    return "\n".join(parts) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description="Summarize model capability probes")
    parser.add_argument("--run", default=None, help="run directory name; defaults to the latest")
    args = parser.parse_args()

    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8")

    runs = sorted(p for p in RUNS_ROOT.iterdir() if p.is_dir()) if RUNS_ROOT.is_dir() else []
    if not runs:
        print("no probe records found; run scripts/probe_models.py first", file=sys.stderr)
        return 2
    run_dir = (RUNS_ROOT / args.run) if args.run else runs[-1]
    if not run_dir.is_dir():
        print(f"run directory not found: {run_dir}", file=sys.stderr)
        return 2

    models = load_run(run_dir)
    markdown = build_markdown(run_dir.name, models)
    (run_dir / "matrix.md").write_text(markdown, encoding="utf-8", newline="\n")
    print(markdown)
    print(f"written to {run_dir / 'matrix.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
